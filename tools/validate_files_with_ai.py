"""Run offline validation checks on Markdown files.

Usage:
    python tools/validate_files_with_ai.py
    python tools/validate_files_with_ai.py --target-dir docs --output-dir reports

This script does not use an AI service or send file contents over the network.
Checks that require a file-specific schema or semantic judgment are reported
as not applicable.
"""

import argparse
import re
import sys
from pathlib import Path


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
PRIVATE_KEY_PATTERN = re.compile(
    r"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----"
)
TOKEN_PATTERNS = (
    re.compile(r"\bgh[pousr]_[A-Za-z0-9]{30,}\b"),
    re.compile(r"\bgithub_pat_[A-Za-z0-9_]{30,}\b"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
)
ACTIVE_CONTENT_PATTERN = re.compile(
    r"<script\b|javascript\s*:|data\s*:\s*text/html", re.IGNORECASE
)


def get_args():
    parser = argparse.ArgumentParser(
        description="Run offline validation checks on Markdown files."
    )
    parser.add_argument(
        "--instruction",
        type=Path,
        default=REPOSITORY_ROOT / "validation-rules.md",
        help="instruction file containing the validation rules",
    )
    parser.add_argument(
        "--target-dir",
        type=Path,
        default=REPOSITORY_ROOT / "instructions",
        help="directory to search recursively for Markdown files",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=REPOSITORY_ROOT / "validation-reports",
        help="directory where per-file validation reports are saved",
    )
    return parser.parse_args()


def collect_targets(target_dir, output_dir):
    output_dir = output_dir.resolve()
    targets = []
    for path in target_dir.rglob("*"):
        if not path.is_file() or path.suffix.lower() != ".md":
            continue
        resolved = path.resolve()
        if resolved == output_dir or output_dir in resolved.parents:
            continue
        targets.append(path)
    return sorted(targets)


def markdown_checks(content):
    checks = [
        (
            "1. Existence and readability",
            "PASS",
            "The file exists and was read as UTF-8.",
        ),
    ]

    fence_count = sum(
        1 for line in content.splitlines() if line.lstrip().startswith("```")
    )
    if fence_count % 2:
        checks.append(
            (
                "2. Format and structure",
                "FAIL",
                "Markdown has an unmatched fenced-code delimiter.",
            )
        )
    else:
        checks.append(
            (
                "2. Format and structure",
                "PASS",
                "The file is UTF-8 Markdown and fenced-code delimiters are balanced.",
            )
        )

    checks.extend(
        [
            (
                "3. Required content",
                "NOT APPLICABLE",
                "No file-specific required sections or schema were provided.",
            ),
            (
                "4. Content validity",
                "NOT APPLICABLE",
                "Domain-specific values cannot be validated without a schema.",
            ),
        ]
    )

    integrity_issues = []
    if not content.strip():
        integrity_issues.append("file is empty")
    if "\x00" in content:
        integrity_issues.append("contains NUL characters")
    if "\ufffd" in content:
        integrity_issues.append("contains Unicode replacement characters")
    checks.append(
        (
            "5. Integrity and completeness",
            "FAIL" if integrity_issues else "PASS",
            "; ".join(integrity_issues)
            if integrity_issues
            else "No empty-file, NUL-character, or decoding-replacement indicators found.",
        )
    )

    safety_issues = []
    if PRIVATE_KEY_PATTERN.search(content):
        safety_issues.append("private-key header detected")
    if any(pattern.search(content) for pattern in TOKEN_PATTERNS):
        safety_issues.append("credential-like token detected")
    if ACTIVE_CONTENT_PATTERN.search(content):
        safety_issues.append("potentially active HTML or URL content detected")
    checks.append(
        (
            "6. Safety and usability",
            "FAIL" if safety_issues else "PASS",
            "; ".join(safety_issues)
            if safety_issues
            else "No known private-key/token patterns or active HTML indicators found.",
        )
    )
    return checks


def format_report(relative_path, checks):
    lines = [
        f"# Offline Validation Report: {relative_path}",
        "",
        "This report was generated by local checks only; no AI service was used.",
        "",
    ]
    for title, status, details in checks:
        lines.extend([f"## {title} — {status}", "", details, ""])
    issues = [
        f"- {title}: {details}"
        for title, status, details in checks
        if status == "FAIL"
    ]
    lines.extend(["## Issues", ""])
    lines.extend(issues if issues else ["- None found by the automated checks."])
    lines.append("")
    return "\n".join(lines)


def main():
    args = get_args()
    instruction_path = args.instruction.resolve()
    target_dir = args.target_dir.resolve()
    output_dir = args.output_dir.resolve()

    if not instruction_path.is_file():
        print(f"Instruction file not found: {instruction_path}", file=sys.stderr)
        return 2
    if not target_dir.is_dir():
        print(f"Target directory not found: {target_dir}", file=sys.stderr)
        return 2
    if output_dir == target_dir or output_dir in target_dir.parents:
        print(
            "Output directory must not be the target directory or one of its parents.",
            file=sys.stderr,
        )
        return 2

    try:
        instruction_text = instruction_path.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        print(f"Could not read instruction file: {exc}", file=sys.stderr)
        return 2
    if not re.search(r"(?m)^\s*1\.\s", instruction_text) or not re.search(
        r"(?m)^\s*6\.\s", instruction_text
    ):
        print(
            "Instruction file does not contain the expected six numbered checks.",
            file=sys.stderr,
        )
        return 2

    targets = collect_targets(target_dir, output_dir)
    if not targets:
        print(f"No Markdown files found in {target_dir}")
        return 0

    print("Target files:")
    for path in targets:
        print(f"- {path}")

    try:
        output_dir.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        print(f"Could not create output directory: {exc}", file=sys.stderr)
        return 2

    failures = 0
    for path in targets:
        relative_path = path.relative_to(target_dir)
        output_path = output_dir / relative_path.with_suffix(".validation.md")
        try:
            content = path.read_text(encoding="utf-8")
            checks = markdown_checks(content)
            report = format_report(relative_path, checks)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            output_path.write_text(report, encoding="utf-8")
            print(f"Saved: {output_path}")
            if any(status == "FAIL" for _, status, _ in checks):
                failures += 1
        except (OSError, UnicodeError) as exc:
            failures += 1
            print(f"Failed: {path}: {exc}", file=sys.stderr)

    if failures:
        print(
            f"Validation completed with {failures} file(s) containing failures "
            "or processing errors.",
            file=sys.stderr,
        )
        return 1
    print(f"Validated {len(targets)} file(s) with local checks.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
